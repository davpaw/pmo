/**
 * Builds data/catalog.generated.json from data/modules.json and the repository.
 *
 * modules.json is the hand-kept declaration of every module (what it owns, what it
 * may depend on, its public entry). This adds what the code can derive: whether
 * the module's paths exist yet, how many files and tests it has, and its dependents.
 *
 * Deterministic by design: nothing here changes unless the structure of the repo
 * changes, so a test can compare the committed file with a fresh build.
 */

import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { globToRegExp } from '../isolation.js'
import { git } from './git.js'

const readJson = (path) => JSON.parse(readFileSync(path, 'utf8'))

/** Tracked and untracked-but-not-ignored files, repo-relative. */
const repoFiles = (root) => git(root, ['ls-files', '--cached', '--others', '--exclude-standard']).split('\n').filter(Boolean)

const TEST_FILE = /\.test\.(?:js|mjs)$/

export const buildCatalog = async ({ root, modulesFile }) => {
  const declared = modulesFile ?? readJson(join(root, 'pmo/data/modules.json'))
  const files = repoFiles(root)
  const entries = Object.entries(declared.modules).sort(([a], [b]) => a.localeCompare(b))
  const ids = new Set(entries.map(([id]) => id))

  const modules = entries.map(([id, module]) => {
    const matchers = (module.owns ?? []).map(globToRegExp)
    const owned = files.filter((file) => matchers.some((matcher) => matcher.test(file)))
    return {
      id,
      title: module.title ?? id,
      summary: module.summary ?? '',
      kind: module.kind ?? 'platform',
      maturity: module.maturity ?? 'planned',
      tags: [...(module.tags ?? [])].sort(),
      owns: module.owns ?? [],
      entry: module.entry ?? null,
      path: (module.owns?.[0] ?? '').replace(/\/?\*\*.*$/, '') || null,
      exists: owned.length > 0,
      files: owned.length,
      hasTests: owned.some((file) => TEST_FILE.test(file)),
      dependsOn: [...(module.dependsOn ?? [])].sort(),
      dependents: [],
      policies: module.policies ?? [],
      gaps: module.gaps ?? [],
    }
  })

  const byId = Object.fromEntries(modules.map((module) => [module.id, module]))
  for (const module of modules) {
    for (const dep of module.dependsOn) {
      if (!ids.has(dep)) throw new Error(`modules.json: ${module.id} depends on unknown module "${dep}"`)
      byId[dep].dependents.push(module.id)
    }
  }
  for (const module of modules) module.dependents.sort()

  return {
    note: 'Generated by `npm run pmo -- build`. Do not edit. Static facts only; live git facts are in pmo/public/data/live.json.',
    counts: {
      modules: modules.length,
      byKind: Object.fromEntries([...new Set(modules.map((module) => module.kind))].sort().map((kind) => [kind, modules.filter((module) => module.kind === kind).length])),
      built: modules.filter((module) => module.exists).length,
      planned: modules.filter((module) => !module.exists).length,
    },
    modules,
  }
}
